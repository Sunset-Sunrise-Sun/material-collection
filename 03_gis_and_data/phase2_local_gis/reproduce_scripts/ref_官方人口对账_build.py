RECON = []
for item, oval, unit, opct, src in OFFICIAL:
    if item.startswith("全市"):
        region = "全市"
        field = item[len("全市"):].replace("户籍", "")
    else:
        m = re.match(r"^(.+?区)[ ]*(.+)$", item)
        if not m:
            raise ValueError("无法解析对账项: %r" % item)
        region, field = m.group(1), m.group(2).strip()
    lr = LOC.get(region)
    if not lr:
        RECON.append({"对账项": item, "官方原文值": oval, "单位": unit, "官方百分比": opct,
                      "本地表值": "**本地表无此区**", "本地百分比": "", "差额": "",
                      "是否一致": "本地缺项", "官方出处": src, "本地字段": "", "备注": ""})
        continue
    fmap = {"总人口": ("total_population", None), "60岁及以上": ("age60_plus", "age60_pct"),
            "65岁及以上": ("age65_plus", "age65_pct"), "80岁及以上": ("age80_plus", "age80_share_of_age60")}
    fld = {"60+": "60岁及以上", "65+": "65岁及以上", "80+": "80岁及以上"}.get(field, field)
    f, pf = fmap[fld]
    lval = int(lr[f])
    lpct = float(lr[pf]) if pf else None
    diff = lval - oval
    same = (diff == 0)
    note = ""
    if same:
        sameS = "一致"
    else:
        sameS = "**不一致**"
        note = "保留双方原值，不覆盖、不修正；差异待核"
    # 百分比核对
    pct_note = ""
    if opct is not None and lpct is not None:
        if abs(lpct - opct) < 1e-9:
            pct_note = "百分比一致"
        else:
            pct_note = "百分比差异：官方%s vs 本地%s" % (opct, lpct)
    RECON.append({"对账项": item, "官方原文值": oval, "单位": unit,
                  "官方百分比": opct if opct is not None else "",
                  "本地表值": lval, "本地百分比": lpct if lpct is not None else "",
                  "差额": diff, "是否一致": sameS,
                  "官方出处": src, "本地字段": "population_2025_registered_district.csv::%s" % f,
                  "备注": (note + ("；" + pct_note if pct_note else "")).strip("；")})

